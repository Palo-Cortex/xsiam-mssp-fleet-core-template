"""Read and write the fleet's configuration files for the setup wizard.

Everything here is a pure function of (repo root, answers): no prompts, no
network, no GitHub. The wizard decides WHAT; this module writes it the same way
every time, keeping the hand-written comments in files it only edits
(defaults.yml, workflows) and regenerating the files it owns (policies.yml,
pin files, tenant profiles).
"""
