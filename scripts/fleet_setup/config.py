# --- tenants -----------------------------------------------------------------
def render_tenant(t):
    lines = [
        f"# Tenant profile — created by scripts/setup_wizard.py. Edit freely;",
        f"# `python scripts/setup_wizard.py doctor` re-checks it.",
        f"tenant: {t['name']}",
        f"display_name: {json.dumps(t.get('display_name') or t['name'])}",
        f"ring: {t['ring']}",
        f"credentials_ref: {t['credentials_ref']}   # GitHub secret {t['credentials_ref']}_CREDS",
    ]
    if t.get("host_token"):
        lines.append(f"host_token: {t['host_token']}          # API host must contain this")
    if t.get("canary"):
        lines.append("canary: true                 # converged first; the rest of the ring waits for it")
    if t.get("customer_namespace"):
        lines.append(f"customer_namespace: {t['customer_namespace']}   # this tenant's owner publishes {t['customer_namespace']}* content")
    lines.append("")
    lines.append("groups: []")
    extras = t.get("extras") or []
    lines += ["extras: []"] if not extras else ["extras:"] + [f"  - {x}" for x in extras]
    lines += ["pin_overrides: {}", "custom: []"]
    return "\n".join(lines) + "\n"


def write_tenant(repo, t):
    p = Path(repo) / "fleet" / "tenants" / f"{t['name']}.yml"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_tenant(t))
    return p


# --- examples ----------------------------------------------------------------
def example_leftovers(repo):
    root = Path(repo)
    found = [f"fleet/tenants/{t}.yml" for t in EXAMPLE_TENANTS
             if (root / "fleet" / "tenants" / f"{t}.yml").exists()]
    found += [f"fleet/groups/{g}.yml" for g in EXAMPLE_GROUPS
              if (root / "fleet" / "groups" / f"{g}.yml").exists()]
    if (root / "Packs" / EXAMPLE_PACK).exists():
        found.append(f"Packs/{EXAMPLE_PACK}/")
    return found


def remove_examples(repo, tenants_=True, groups=True, pack=True):
    root = Path(repo)
    removed = []
    if tenants_:
        for t in EXAMPLE_TENANTS:
            f = root / "fleet" / "tenants" / f"{t}.yml"
            if f.exists():
                f.unlink()
                removed.append(str(f.relative_to(root)))
    if groups:
        for g in EXAMPLE_GROUPS:
            f = root / "fleet" / "groups" / f"{g}.yml"
            if f.exists():
                f.unlink()
                removed.append(str(f.relative_to(root)))
    if pack and (root / "Packs" / EXAMPLE_PACK).exists():
        shutil.rmtree(root / "Packs" / EXAMPLE_PACK)
        removed.append(f"Packs/{EXAMPLE_PACK}/")
    return removed


