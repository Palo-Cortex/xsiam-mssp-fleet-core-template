_NAME = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,38}[a-z0-9])?$")
_PREFIX = re.compile(r"^[a-z0-9]+-$")


# --- names -------------------------------------------------------------------
def tenant_name_error(name, existing=()):
    if not _NAME.match(name or ""):
        return ("use 1-40 lowercase letters, digits or hyphens (no leading/trailing "
                "hyphen), e.g. acme-prod")
    if name in existing:
        return f"a tenant called '{name}' already exists"
    return None


def prefix_error(prefix):
    if not _PREFIX.match(prefix or ""):
        return "use lowercase letters/digits ending in a hyphen, e.g. acme-"
    return None


def credentials_ref(name):
    """Tenant name -> GitHub secret prefix (A-Z, 0-9, _; not starting with a
    digit or GITHUB_)."""
    ref = re.sub(r"[^A-Z0-9]", "_", name.upper())
    if ref[0].isdigit() or ref.startswith("GITHUB_"):
        ref = "T_" + ref
    return ref


def environment_for(ring, rings):
    if ring == MSSP_RING:
        return ENV_MSSP
    return ENV_PROD if ring == rings[-1] else ENV_NONPROD


# --- reading -----------------------------------------------------------------
def load_yaml(path):
    p = Path(path)
    return (yaml.safe_load(p.read_text()) or {}) if p.exists() else {}


def policies(repo):
    return load_yaml(Path(repo) / "fleet" / "policies.yml")


def chain(repo):
    """The promotion chain from policies.yml, head first (excludes mssp)."""
    return list(policies(repo).get("promotion_order") or [])


def tenants(repo):
    return {f.stem: load_yaml(f) for f in sorted((Path(repo) / "fleet" / "tenants").glob("*.yml"))}


def pins(repo, ring):
    return load_yaml(Path(repo) / "fleet" / "pins" / f"{ring}.yml").get("pins") or {}


def defaults(repo):
    return load_yaml(Path(repo) / "fleet" / "defaults.yml")


# --- policies.yml ------------------------------------------------------------
def render_policies(rings, soak, change_window=None, require_lock=None,
                    max_parallel=None, mssp_ring=False):
    """policies.yml text for a promotion chain `rings` (head first)."""
    require_lock = require_lock or {}
    max_parallel = max_parallel or {}
    path = " -> ".join(rings)
    out = [
        "# ============================================================================",
        "# policies.yml  —  ring promotion policy (machine-checked, not remembered)",
        "# ----------------------------------------------------------------------------",
        f"# Generated by scripts/setup_wizard.py for the promotion path: {path}",
        "# Safe to edit by hand; `python scripts/setup_wizard.py doctor` re-checks it.",
        "#",
        "#   source              the ring a version must come from (null = head ring)",
        "#   min_soak_days       days the version must have run in `source` first",
        "#   require_change_window / change_windows   UTC windows prod may merge/deploy in",
        "#   require_lock        every pin needs a sha256 entry in artifacts.lock.yml",
        "#   max_parallel        tenants deployed at once (after `canary: true` tenants)",
        "#   environment         GitHub Environment the ring's tenant jobs run in",
        "#",
        "# Break-glass rollback: label a PR `rollback` to return a ring to a version it",
        "# already ran (see docs/runbook.md). Changes to this file only take effect",
        "# once merged — a PR is always judged by the policy already on main.",
        "# ============================================================================",
        "",
        f"promotion_order: [{', '.join(rings)}]",
        "",
        "rings:",
    ]
    if mssp_ring:
        out += [
            f"  {MSSP_RING}:",
            "    source: null            # the MSSP's own parent tenant — outside the customer chain",
            "    min_soak_days: 0",
            "    require_dry_run: false",
            f"    environment: {ENV_MSSP}",
            "",
        ]
    for i, ring in enumerate(rings):
        source = rings[i - 1] if i else None
        last = i == len(rings) - 1
        out.append(f"  {ring}:")
        if source is None:
            out.append("    source: null            # head of the chain — versions are pinned here first")
        else:
            out.append(f"    source: {source}              # a {ring} pin must already be in {source}.yml")
        out.append(f"    min_soak_days: {int(soak.get(ring, 0)) if source else 0}")
        out.append(f"    require_dry_run: {'true' if source else 'false'}")
        if last and change_window:
            out += [
                "    require_change_window: true",
                "    change_windows:         # UTC",
                f"      - days: [{', '.join(change_window['days'])}]",
                f"        start: \"{change_window['start']}\"",
                f"        end: \"{change_window['end']}\"",
            ]
        if source:
            out.append(f"    require_lock: {'true' if require_lock.get(ring) else 'false'}")
            out.append(f"    max_parallel: {int(max_parallel.get(ring, 5 if last else 10))}")
        out.append(f"    environment: {ENV_PROD if last else ENV_NONPROD}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# --- pin files ---------------------------------------------------------------
def render_pins(ring, source, pinmap):
    if source is None:
        role = (f"Head of the chain: versions are pinned HERE first, then promoted\n"
                f"# forward. Edits merge freely (no soak / no-skip).")
    else:
        role = (f"Fed by promotion from {source}.yml (python scripts/promote.py --pack <id>\n"
                f"# --to {ring}, or the promote workflow). ring-gate enforces no-skip + soak.")
    lines = [
        "# ============================================================================",
        f"# pins/{ring}.yml  —  exact pack versions for the {ring.upper()} ring",
        "# ----------------------------------------------------------------------------",
        f"# {role}",
        "# Every pack a tenant in this ring composes needs a pin here.",
        "# ============================================================================",
        f"ring: {ring}",
        "pins:" if pinmap else "pins: {}",
    ]
    lines += [f"  {k}: {v}" for k, v in pinmap.items()]
    return "\n".join(lines) + "\n"


def write_pins(repo, ring, source, pinmap):
    p = Path(repo) / "fleet" / "pins" / f"{ring}.yml"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_pins(ring, source, dict(pinmap)))


def set_rings(repo, rings, mssp_ring=False):
    """Make fleet/pins/ hold exactly one file per ring; returns removed rings."""
    pin_dir = Path(repo) / "fleet" / "pins"
    keep = set(rings) | ({MSSP_RING} if mssp_ring else set())
    removed = []
    for f in sorted(pin_dir.glob("*.yml")):
        if f.stem not in keep:
            f.unlink()
            removed.append(f.stem)
    for i, ring in enumerate(rings):
        if not (pin_dir / f"{ring}.yml").exists():
            write_pins(repo, ring, rings[i - 1] if i else None, {})
    if mssp_ring and not (pin_dir / f"{MSSP_RING}.yml").exists():
        write_pins(repo, MSSP_RING, None, {})
    return removed


# --- workflow choice lists ---------------------------------------------------
def _set_options(text, input_name, values, default):
    """Rewrite `options: [...]` and `default:` of one workflow_dispatch input."""
    # the input's key line plus every line indented deeper than it
    pat = re.compile(rf"(\n([ ]+){re.escape(input_name)}:[ ]*\n(?:\2[ ]+.*\n)*)")
    m = pat.search(text)
    if not m:
        raise ValueError(f"workflow input '{input_name}' not found")
    block = m.group(1)
    if "options:" not in block:
        raise ValueError(f"workflow input '{input_name}' has no options list")
    new = re.sub(r"(options:\s*)\[[^\]]*\]", lambda mm: f"{mm.group(1)}[{', '.join(values)}]", block)
    new = re.sub(r"(default:\s*)\S+", lambda mm: f"{mm.group(1)}{default}", new, count=1)
    return text[:m.start(1)] + new + text[m.end(1):]


def update_workflow_choices(repo, rings, mssp_ring=False):
    wf = Path(repo) / ".github" / "workflows"
    all_rings = list(rings) + ([MSSP_RING] if mssp_ring else [])
    conv = wf / "converge.yml"
    conv.write_text(_set_options(conv.read_text(), "ring", all_rings, rings[0]))
    prom = wf / "promote.yml"
    prom.write_text(_set_options(prom.read_text(), "to_ring", rings[1:], rings[1]))


def workflow_choices(repo):
    """{'converge': [...], 'promote': [...]} as currently written."""
    out = {}
    wf = Path(repo) / ".github" / "workflows"
    for name, key in (("converge", "ring"), ("promote", "to_ring")):
        d = load_yaml(wf / f"{name}.yml")
        on = d.get("on") or d.get(True) or {}
        out[name] = ((on.get("workflow_dispatch") or {}).get("inputs") or {}).get(key, {}).get("options", [])
    return out


# --- defaults.yml (edited in place, comments kept) ---------------------------
def _replace_list_block(text, key, items):
    """Replace the YAML list under a top-level `key:` (block or flow style)."""
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if re.match(rf"^{re.escape(key)}:", line):
            j = i + 1      # the block = following indented lines (a blank line ends it)
            while j < len(lines) and lines[j].startswith((" ", "\t")):
                j += 1
            new = [f"{key}: []\n"] if not items else [f"{key}:\n"] + [f"  - {x}\n" for x in items]
            return "".join(lines[:i] + new + lines[j:])
    sep = "" if text.endswith("\n") else "\n"
    body = f"{key}: []\n" if not items else f"{key}:\n" + "".join(f"  - {x}\n" for x in items)
    return text + sep + body


def update_defaults(repo, base=None, release_base=None, customer_namespaces=None):
    p = Path(repo) / "fleet" / "defaults.yml"
    text = p.read_text()
    if base is not None:
        text = _replace_list_block(text, "base", base)
    if customer_namespaces is not None:
        text = _replace_list_block(text, "customer_namespaces", customer_namespaces)
    if release_base is not None:
        text, n = re.subn(r"(?m)^(\s+release_base:\s*).*$",
                          lambda m: f"{m.group(1)}{release_base}", text)
        if not n:
            raise ValueError("defaults.yml has no mssp_catalog.release_base")
    p.write_text(text)
    yaml.safe_load(text)      # never leave a broken file behind


