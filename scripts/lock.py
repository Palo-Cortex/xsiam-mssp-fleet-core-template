#!/usr/bin/env python3
"""
lock.py — the artifact lock: pack@version -> exact zip URL + sha256.

A pin names a VERSION; the lock names the BYTES. Without it, a pinned version
is only as reproducible as (a) the upstream catalog read at deploy time (tip of
main unless catalog.pinned_commit is set), (b) catalog.py's best-effort URL
retagging when the catalog publishes a different version, and (c) a GitHub
release asset that can be deleted and re-uploaded. The lock freezes all three:
converge deploys a locked pack from its locked URL and refuses bytes whose
sha256 doesn't match.

    fleet/artifacts.lock.yml
    artifacts:
      soc-optimization-unified:
        3.10.3:
          zip_url: https://github.com/.../soc-optimization-unified-v3.10.3.zip
          sha256: 9f2c...

Entries are keyed by pack@version, not by ring — promotion copies a pin, and
the lock entry written when the version entered dev serves qa and prod as-is.

Rings with `require_lock: true` in fleet/policies.yml must have a lock entry
for every non-`local` pin (ring pins + pin_overrides of that ring's tenants):
`--check` enforces it offline (ring-gate, check.sh) and deploy_tenant.py
refuses to --apply an unlocked pack in such a ring.

Usage:
    python scripts/lock.py --check                      # offline; exit 1 if missing
    python scripts/lock.py --write                      # lock every unlocked pin (network)
    python scripts/lock.py --write --pack X --version 1.2.3
    python scripts/lock.py --write --allow-retag        # accept catalog!=pin URLs
"""
import argparse
import hashlib
import sys
from pathlib import Path

import yaml

import resolve

LOCK_NAME = "artifacts.lock.yml"
_HEADER = """\
# ============================================================================
# artifacts.lock.yml — GENERATED by scripts/lock.py; review, don't hand-edit.
# pack -> version -> {zip_url, sha256}. converge deploys a locked pack from
# zip_url and refuses bytes whose sha256 differs. Rings with
# `require_lock: true` (fleet/policies.yml) need an entry for every pin.
# ============================================================================
"""


class LockError(Exception):
    pass


def lock_path():
    return resolve.FLEET / LOCK_NAME


def load_lock():
    """{pack: {version: {zip_url, sha256}}} ({} when there is no lock file)."""
    p = lock_path()
    if not p.exists():
        return {}
    data = yaml.safe_load(p.read_text()) or {}
    return {str(k): {str(v): e for v, e in (vs or {}).items()}
            for k, vs in (data.get("artifacts") or {}).items()}


def save_lock(lock):
    ordered = {k: {v: lock[k][v] for v in sorted(lock[k])} for k in sorted(lock)}
    lock_path().write_text(_HEADER + yaml.safe_dump({"artifacts": ordered},
                                                    sort_keys=False))


def lock_entry(lock, pack, version):
    return (lock.get(pack) or {}).get(str(version))


def ring_policy(ring):
    f = resolve.FLEET / "policies.yml"
    if not f.exists():
        return {}
    return ((yaml.safe_load(f.read_text()) or {}).get("rings") or {}).get(ring) or {}


def ring_requires_lock(ring):
    return bool(ring_policy(ring).get("require_lock"))


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def pinned(ring_filter=None):
    """[(ring, where, pack, version)] for every exact pin: ring pin files plus
    each tenant's pin_overrides (attributed to the tenant's ring)."""
    out = []
    for f in sorted((resolve.FLEET / "pins").glob("*.yml")):
        ring = f.stem
        for pack, ver in ((yaml.safe_load(f.read_text()) or {}).get("pins") or {}).items():
            out.append((ring, f"fleet/pins/{f.name}", pack, ver))
    for f in sorted((resolve.FLEET / "tenants").glob("*.yml")):
        t = yaml.safe_load(f.read_text()) or {}
        for pack, ver in (t.get("pin_overrides") or {}).items():
            out.append((t.get("ring"), f"fleet/tenants/{f.name} pin_overrides", pack, ver))
    return [(r, w, p, str(v)) for r, w, p, v in out
            if v not in (None, "", "local") and (ring_filter is None or r == ring_filter)]


def missing_entries(lock=None):
    """Pins in require_lock rings with no lock entry: [(where, pack, version)]."""
    lock = load_lock() if lock is None else lock
    return [(w, p, v) for r, w, p, v in pinned()
            if ring_requires_lock(r) and not lock_entry(lock, p, v)]


def write(packs=None, version=None, allow_retag=False):
    """Lock every unlocked pin (or just --pack [--version]). Network."""
    # imported lazily: --check must stay offline and dependency-free
    import os
    import shutil
    from catalog import resolve_artifact
    from deploy_tenant import download

    defaults = yaml.safe_load((resolve.FLEET / "defaults.yml").read_text())
    cat_url = defaults["catalog"]["url"]
    commit = defaults["catalog"].get("pinned_commit")
    lock = load_lock()
    todo = sorted({(p, v) for _r, _w, p, v in pinned()})
    if packs:
        todo = [(p, v) for p, v in todo if p in packs]
        if version:
            todo = [(p, version) for p in packs]
    added = 0
    for pack, ver in todo:
        if lock_entry(lock, pack, ver):
            continue
        art = resolve_artifact(pack, ver, cat_url, commit)
        if not art.get("zip_url"):
            raise LockError(f"{pack} {ver}: catalog has no zip URL")
        if not art.get("exact") and not allow_retag:
            raise LockError(
                f"{pack} {ver}: the catalog publishes {art.get('catalog_version')}, so "
                f"the URL was guessed by retagging ({art['zip_url']}). Verify it, then "
                f"re-run with --allow-retag")
        path = download(art["zip_url"])
        try:
            digest = sha256_file(path)
        finally:
            shutil.rmtree(os.path.dirname(path), ignore_errors=True)
        lock.setdefault(pack, {})[ver] = {"zip_url": art["zip_url"], "sha256": digest}
        print(f"locked {pack} {ver}  sha256:{digest[:12]}…  {art['zip_url']}")
        added += 1
    save_lock(lock) if added else None
    print(f"{added} new lock entr{'y' if added == 1 else 'ies'}")


def main():
    ap = argparse.ArgumentParser(description="Generate / check the artifact lock.")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    ap.add_argument("--pack", action="append", help="limit --write to this pack (repeatable)")
    ap.add_argument("--version", help="with one --pack: lock this version")
    ap.add_argument("--allow-retag", action="store_true",
                    help="accept a URL guessed from a catalog that publishes another version")
    args = ap.parse_args()

    if args.check:
        missing = missing_entries()
        if missing:
            print(f"✗ {len(missing)} pin(s) in require_lock rings have no lock entry:")
            for where, pack, ver in missing:
                print(f"  - {where}: {pack} {ver}")
            print("  run: python scripts/lock.py --write  (or the promote workflow does it)")
            sys.exit(1)
        print("✓ lock — every pin in a require_lock ring is locked")
        return
    try:
        write(args.pack, args.version, args.allow_retag)
    except Exception as e:  # noqa: BLE001 — CatalogError/DeployError/LockError alike
        sys.exit(f"ERROR: {e}")


if __name__ == "__main__":
    main()
